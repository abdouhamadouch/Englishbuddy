# ============================================================
# DATA MODELS
# ============================================================

@dataclass
class MediaItem:
    chat_id: int
    message_id: int
    title: str

    # audio / video
    kind: str

    requester_id: int

    # Topic where the user requested the media.
    thread_id: Optional[int] = None

    # Downloaded local file.
    temp_path: Optional[str] = None


@dataclass
class PlayerState:
    queue: deque
    current: Optional[MediaItem] = None

    paused: bool = False
    muted: bool = False

    volume: int = 100

    # off / one / all
    repeat: str = "off"

    starting: bool = False

    # Prevent a delayed stream_end event generated by manual
    # skip/stop from interfering with the next track.
    suppress_next_end: bool = False


PLAYERS: dict[int, PlayerState] = {}
CHAT_LOCKS: dict[int, asyncio.Lock] = {}


# ============================================================
# PLAYER STATE
# ============================================================

def _state(chat_id: int) -> PlayerState:
    if chat_id not in PLAYERS:
        PLAYERS[chat_id] = PlayerState(queue=deque())

    return PLAYERS[chat_id]


def _lock(chat_id: int) -> asyncio.Lock:
    if chat_id not in CHAT_LOCKS:
        CHAT_LOCKS[chat_id] = asyncio.Lock()

    return CHAT_LOCKS[chat_id]


# ============================================================
# MEDIA DETECTION
# ============================================================

def _media_from_message(message) -> tuple[str, str] | None:
    """
    Return:
        ("audio", title)
        ("video", title)

    for Telegram media that can be downloaded and processed.
    """

    if not message:
        return None

    audio = getattr(message, "audio", None)

    if audio:
        return (
            "audio",
            getattr(audio, "file_name", None) or "Audio",
        )

    video = getattr(message, "video", None)

    if video:
        return (
            "video",
            getattr(video, "file_name", None) or "Video",
        )

    voice = getattr(message, "voice", None)

    if voice:
        return (
            "audio",
            "Voice message",
        )

    document = getattr(message, "document", None)

    if document:
        mime = (
            getattr(document, "mime_type", None)
            or ""
        ).lower()

        if mime.startswith("audio/"):
            return (
                "audio",
                getattr(document, "file_name", None)
                or "Audio",
            )

        if mime.startswith("video/"):
            return (
                "video",
                getattr(document, "file_name", None)
                or "Video",
            )

    return None


def _source_message(update: Update):
    message = update.effective_message

    if not message:
        return None

    if message.reply_to_message:
        return message.reply_to_message

    return None


def _title(item: MediaItem) -> str:
    return item.title or item.kind.title()


# ============================================================
# PERMISSIONS
# ============================================================

async def _is_admin(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
) -> bool:

    user = update.effective_user
    message = update.effective_message

    if not user or not message:
        return False

    if OWNER_ID is not None and user.id == OWNER_ID:
        return True

    # Private chats do not need admin permissions.
    if message.chat.type == "private":
        return True

    try:
        member = await context.bot.get_chat_member(
            message.chat.id,
            user.id,
        )

        return member.status in ADMIN_STATUSES

    except Exception:
        log.exception(
            "Admin check failed user=%s chat=%s",
            user.id,
            message.chat.id,
        )

        return False


async def _require_admin(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
) -> bool:

    if await _is_admin(update, context):
        return True

    message = update.effective_message

    if message:
        await message.reply_text(
            "❌ هذا الأمر متاح للمشرفين فقط."
        )

    return False


