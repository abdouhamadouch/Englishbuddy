# ============================================================

async def skip_handler(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
) -> None:

    if not await _require_admin(
        update,
        context,
    ):
        return

    message = update.effective_message

    if not message:
        return

    chat_id = message.chat.id

    async with _lock(chat_id):

        state = _state(chat_id)

        if state.current is None:

            await message.reply_text(
                "ℹ️ Nothing is playing."
            )

            return

        old = state.current

        # Prevent the delayed stream_end event
        # from treating the new track as finished.
        state.suppress_next_end = True

        await _safe_stop_call(
            chat_id
        )

        await _cleanup_path(
            old.temp_path
        )

        state.current = None
        state.paused = False
        state.starting = False

        started = await _start_current(
            chat_id,
            context,
        )

        if started:

            await message.reply_text(
                "⏭ Skipped."
            )

        else:

            state.suppress_next_end = False

            await message.reply_text(
                "⏭ Skipped. Queue is empty."
            )

            await _safe_leave(
                chat_id
            )


