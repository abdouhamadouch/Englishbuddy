# ============================================================
# BUTTON CALLBACKS
# ============================================================

async def _callback_handler(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
) -> None:

    query = update.callback_query

    if not query:
        return

    parts = (
        query.data or ""
    ).split(":")

    if (
        len(parts) != 3
        or parts[0] != "mp"
    ):
        return

    try:

        chat_id = int(
            parts[1]
        )

    except ValueError:
        return

    action = parts[2]

    if query.message is None:
        return

    # --------------------------------------------------------
    # Hide buttons
    # --------------------------------------------------------

    if action == "hide":

        try:

            await query.edit_message_reply_markup(
                reply_markup=None
            )

            await query.answer(
                "Buttons hidden."
            )

        except Exception:

            log.exception(
                "MEDIA: failed to hide buttons."
            )

        return

    # --------------------------------------------------------
    # Admin check
    # --------------------------------------------------------

    if not await _is_admin(
        update,
        context,
    ):

        await query.answer(
            "Admins only.",
            show_alert=True,
        )

        return

    # --------------------------------------------------------
    # Execute action
    # --------------------------------------------------------

    if action == "pause":

        await query.answer()
        await pause_handler(
            update,
            context,
        )

    elif action == "resume":

        await query.answer()
        await resume_handler(
            update,
            context,
        )

    elif action == "skip":

        await query.answer()
        await skip_handler(
            update,
            context,
        )

    elif action == "stop":

        await query.answer()
        await stop_handler(
            update,
            context,
        )

    elif action == "queue":

        await query.answer()
        await queue_handler(
            update,
            context,
        )

    elif action == "repeat":

        await query.answer()
        await repeat_handler(
            update,
            context,
        )


