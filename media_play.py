# SHUTDOWN
# ============================================================

async def shutdown_media_player() -> None:

    global USER_CLIENT
    global CALLS
    global _ENGINE_READY
    global _EVENTS_REGISTERED
    global BOT_INSTANCE

    log.info(
        "MEDIA SHUTDOWN: starting cleanup..."
    )

    for chat_id in list(
        PLAYERS
    ):

        try:

            async with _lock(
                chat_id
            ):

                state = PLAYERS[
                    chat_id
                ]

                state.suppress_next_end = True

                if CALLS is not None:

                    await _safe_leave(
                        chat_id
                    )

                if state.current:

                    await _cleanup_path(
                        state.current.temp_path
                    )

                for item in state.queue:

                    await _cleanup_path(
                        item.temp_path
                    )

                state.queue.clear()
                state.current = None
                state.paused = False
                state.starting = False

        except Exception:

            log.exception(
                "MEDIA SHUTDOWN: "
                "chat cleanup failed chat=%s",
                chat_id,
            )

    PLAYERS.clear()
    CHAT_LOCKS.clear()

    if CALLS is not None:

        try:

            result = CALLS.stop()

            if inspect.isawaitable(result):

                await asyncio.wait_for(
                    result,
                    20,
                )

            log.info(
                "MEDIA SHUTDOWN: PyTgCalls stopped."
            )

        except Exception:

            log.exception(
                "MEDIA SHUTDOWN: "
                "PyTgCalls stop failed."
            )

    CALLS = None
    _EVENTS_REGISTERED = False

    if USER_CLIENT is not None:

        try:

            if (
                getattr(
                    USER_CLIENT,
                    "is_connected",
                    False,
                )
                or getattr(
                    USER_CLIENT,
                    "is_started",
                    False,
                )
            ):

                await asyncio.wait_for(
                    USER_CLIENT.stop(),
                    20,
                )

            log.info(
                "MEDIA SHUTDOWN: Pyrogram stopped."
            )

        except Exception:

            log.exception(
                "MEDIA SHUTDOWN: "
                "Pyrogram stop failed."
            )

    USER_CLIENT = None
    BOT_INSTANCE = None
    _ENGINE_READY = False

    log.info(
        "MEDIA SHUTDOWN: complete."
    )


async def _post_shutdown(
    application: Application,
) -> None:

    await shutdown_media_player()


