# ============================================================
# QUEUE DISPLAY
# ============================================================

def _format_queue(state: PlayerState) -> str:

    lines = []

    if state.current:
        status = (
            "⏸ Paused"
            if state.paused
            else "▶️ Playing"
        )

        lines.append(
            f"🎵 {status}: {state.current.title}"
        )

    if state.queue:
        lines.append("")
        lines.append("📋 Queue:")

        for index, item in enumerate(state.queue, 1):
            lines.append(
                f"{index}. {item.title}"
            )

    if not lines:
        return "📋 Queue is empty."

    return "\n".join(lines)


# ============================================================
# MEDIA ENGINE
# ============================================================

async def _ensure_engine() -> None:

    global USER_CLIENT
    global CALLS
    global _ENGINE_READY

    if (
        _ENGINE_READY
        and USER_CLIENT is not None
        and CALLS is not None
    ):
        if (
            getattr(USER_CLIENT, "is_connected", False)
            or getattr(USER_CLIENT, "is_started", False)
        ):
            return

    async with _ENGINE_LOCK:

        if (
            _ENGINE_READY
            and USER_CLIENT is not None
            and CALLS is not None
        ):
            if (
                getattr(USER_CLIENT, "is_connected", False)
                or getattr(USER_CLIENT, "is_started", False)
            ):
                return

        if not API_ID or not API_HASH or not SESSION_STRING:
            raise RuntimeError(
                "Missing API_ID, API_HASH, or SESSION_STRING "
                "for the media player."
            )

        if PyTgCalls is None:
            raise RuntimeError(
                "PyTgCalls could not be imported. "
                "Check py-tgcalls installation."
            )

        if MediaStream is None:
            raise RuntimeError(
                "MediaStream could not be imported from PyTgCalls."
            )

        # ----------------------------------------------------
        # FFmpeg checks
        # ----------------------------------------------------

        ffmpeg = shutil.which("ffmpeg")
        ffprobe = shutil.which("ffprobe")

        log.info(
            "MEDIA ENGINE: ffmpeg=%s",
            ffmpeg or "NOT FOUND",
        )

        log.info(
            "MEDIA ENGINE: ffprobe=%s",
            ffprobe or "NOT FOUND",
        )

        if not ffmpeg:
            raise RuntimeError(
                "FFmpeg was not found in the system PATH."
            )

        if not ffprobe:
            log.warning(
                "FFprobe was not found in the system PATH. "
                "Some media formats may fail."
            )

        # ----------------------------------------------------
        # Versions
        # ----------------------------------------------------

        try:
            import importlib.metadata as metadata

            pyrogram_version = metadata.version(
                "pyrogram"
            )

            pytgcalls_version = metadata.version(
                "py-tgcalls"
            )

        except Exception:
            pyrogram_version = "unknown"
            pytgcalls_version = "unknown"

        log.info(
            "MEDIA ENGINE: pyrogram=%s pytgcalls=%s",
            pyrogram_version,
            pytgcalls_version,
        )

        # ----------------------------------------------------
        # Pyrogram
        # ----------------------------------------------------

        if USER_CLIENT is None:
            USER_CLIENT = Client(
                "fixmyenglish_player",
                api_id=API_ID,
                api_hash=API_HASH,
                session_string=SESSION_STRING,
                in_memory=True,
            )

        if not getattr(
            USER_CLIENT,
            "is_connected",
            False,
        ):

            log.info(
                "MEDIA ENGINE: starting Pyrogram user client..."
            )

            await USER_CLIENT.start()

            log.info(
                "MEDIA ENGINE: Pyrogram user client started."
            )

        # ----------------------------------------------------
        # PyTgCalls
        # ----------------------------------------------------

        if CALLS is None:

            log.info(
                "MEDIA ENGINE: creating PyTgCalls..."
            )

            CALLS = PyTgCalls(USER_CLIENT)

            log.info(
                "MEDIA ENGINE: starting PyTgCalls..."
            )

            result = CALLS.start()

            if inspect.isawaitable(result):
                await result

            log.info(
                "MEDIA ENGINE: PyTgCalls started."
            )

            _register_call_events()

        _ENGINE_READY = True


# ============================================================
# STREAM EVENTS
# ============================================================

def _register_call_events() -> None:

    global _EVENTS_REGISTERED

    if _EVENTS_REGISTERED:
        return

    if (
        CALLS is None
        or call_filters is None
        or StreamEnded is None
    ):
        raise RuntimeError(
            "PyTgCalls event API is unavailable."
        )

    @CALLS.on_update(call_filters.stream_end())
    async def _stream_end_handler(_, update):

        chat_id = getattr(
            update,
            "chat_id",
            None,
        )

        if chat_id is None:
            return

        log.info(
            "MEDIA EVENT: stream ended chat=%s",
            chat_id,
        )

        asyncio.create_task(
            _handle_stream_end(int(chat_id))
        )

    _EVENTS_REGISTERED = True


# ============================================================
# CALL CONTROL
# ============================================================

async def _safe_leave(chat_id: int) -> None:

    if CALLS is None:
        return

    try:
        result = CALLS.leave_call(chat_id)

        if inspect.isawaitable(result):
            await asyncio.wait_for(
                result,
                20,
            )

        log.info(
            "MEDIA: left voice chat=%s",
            chat_id,
        )

    except Exception as exc:
        log.warning(
            "MEDIA: leave_call failed chat=%s error=%r",
            chat_id,
            exc,
        )


async def _safe_stop_call(chat_id: int) -> None:
    await _safe_leave(chat_id)


# ============================================================
# DOWNLOAD
# ============================================================

async def _download_item(
    item: MediaItem,
) -> str:

    if USER_CLIENT is None:
        raise RuntimeError(
            "Pyrogram media client is not running."
        )

    source = await asyncio.wait_for(
        USER_CLIENT.get_messages(
            item.chat_id,
            item.message_id,
        ),
        timeout=MESSAGE_TIMEOUT,
    )

    if not source:
        raise RuntimeError(
            "The source Telegram message could not be found."
        )

    source_media = _media_from_message(source)

    if source_media is None:
        raise RuntimeError(
            "The source message no longer contains playable media."
        )

    prefix = (
        f"fixmyenglish_"
        f"{item.chat_id}_"
        f"{item.message_id}_"
    )

    path = await asyncio.wait_for(
        USER_CLIENT.download_media(
            source,
            file_name=str(
                TEMP_ROOT / prefix
            ),
        ),
        timeout=DOWNLOAD_TIMEOUT,
    )

    if not path:
        raise RuntimeError(
            "Telegram media download returned no file."
        )

    log.info(
        "MEDIA DOWNLOAD: chat=%s message=%s path=%s",
        item.chat_id,
        item.message_id,
        path,
    )

    return str(path)


async def _cleanup_path(
    path: Optional[str],
) -> None:

    if not path:
        return

    try:
        await asyncio.to_thread(
            Path(path).unlink,
            True,
        )

    except FileNotFoundError:
        pass

    except Exception:
        log.exception(
            "MEDIA: failed to delete temp file %s",
            path,
        )


# ============================================================
# NOW PLAYING
# ============================================================

async def _send_now_playing(
    chat_id: int,
    item: MediaItem,
    context: ContextTypes.DEFAULT_TYPE | None = None,
) -> None:

    bot = None

    if context is not None:
        bot = context.bot

    elif BOT_INSTANCE is not None:
        bot = BOT_INSTANCE

    if bot is None:
        log.warning(
            "MEDIA: no Telegram bot instance available "
            "for now-playing message."
        )
        return

    send_kwargs = {
        "chat_id": chat_id,
        "text": (
            "🎵 <b>Now Playing</b>\n\n"
            f"• {item.title}\n"
            f"• Type: {item.kind}\n"
            f"• Requested by: {item.requester_id}"
        ),
        "parse_mode": "HTML",
        "reply_markup": _buttons(chat_id),
    }

    # Critical for Telegram forum topics.
    # None means General/non-topic chat.
    if item.thread_id is not None:
        send_kwargs["message_thread_id"] = item.thread_id

    try:
        await bot.send_message(**send_kwargs)

    except Exception:
        log.exception(
            "MEDIA: failed to send now-playing message "
            "chat=%s thread=%s",
            chat_id,
            item.thread_id,
        )


# ============================================================
# STREAM CREATION
# ============================================================

def _build_stream(
    item: MediaItem,
    path: str,
):
    """
    Build the correct PyTgCalls stream.

    audio:
        video is explicitly ignored.

    video:
        both audio and video are streamed.
    """

    if MediaStream is None:
        raise RuntimeError(
            "PyTgCalls MediaStream is unavailable."
        )

    if item.kind == "video":

        if AudioQuality is None:
            raise RuntimeError(
                "PyTgCalls AudioQuality is unavailable."
            )

        if VideoQuality is None:
            raise RuntimeError(
                "PyTgCalls VideoQuality is unavailable."
            )

        return MediaStream(
            path,
            AudioQuality.HIGH,
            VideoQuality.HD_720p,
        )

    # Audio-only mode.
    return MediaStream(
        path,
        video_flags=MediaStream.Flags.IGNORE,
    )


# ============================================================
# START CURRENT TRACK
# ============================================================

async def _start_current(
    chat_id: int,
    context: ContextTypes.DEFAULT_TYPE | None = None,
) -> bool:

    state = _state(chat_id)

    if state.current is None:

        if not state.queue:
            return False

        state.current = state.queue.popleft()

    if state.starting:
        return False

    state.starting = True

    item = state.current

    try:

        log.info(
            "MEDIA START: chat=%s message=%s "
            "kind=%s title=%r thread=%s",
            chat_id,
            item.message_id,
            item.kind,
            item.title,
            item.thread_id,
        )

        await _ensure_engine()

        # ----------------------------------------------------
        # Download
        # ----------------------------------------------------

        if (
            item.temp_path
            and Path(item.temp_path).exists()
        ):
            path = item.temp_path

        else:

            log.info(
                "MEDIA START: downloading "
                "chat=%s message=%s",
                chat_id,
                item.message_id,
            )

            path = await _download_item(item)

            item.temp_path = path

        # ----------------------------------------------------
        # Build stream
        # ----------------------------------------------------

        stream = _build_stream(
            item,
            path,
        )

        log.info(
            "MEDIA START: calling PyTgCalls.play "
            "chat=%s path=%s kind=%s",
            chat_id,
            path,
            item.kind,
        )

        result = CALLS.play(
            chat_id,
            stream,
        )

        if inspect.isawaitable(result):
            await asyncio.wait_for(
                result,
                PLAY_TIMEOUT,
            )

        state.paused = False
        state.muted = False
        state.starting = False

        log.info(
            "MEDIA START: playback started "
            "chat=%s title=%r kind=%s",
            chat_id,
            item.title,
            item.kind,
        )

        await _send_now_playing(
            chat_id,
            item,
            context,
        )

        return True

    except asyncio.TimeoutError:

        log.error(
            "MEDIA START TIMEOUT: "
            "chat=%s message=%s",
            chat_id,
            item.message_id,
        )

        await _safe_leave(chat_id)

    except Exception as exc:

        log.exception(
            "MEDIA START FAILED: "
            "chat=%s message=%s error=%r",
            chat_id,
            item.message_id,
            exc,
        )

        await _safe_leave(chat_id)

    state.starting = False

    failed = state.current
    state.current = None

    if failed:
        await _cleanup_path(
            failed.temp_path
        )

    # Try the next queued item.
    if state.queue:
        return await _start_current(
            chat_id,
            context,
        )

    return False


# ============================================================
# STREAM END
# ============================================================

async def _handle_stream_end(
    chat_id: int,
) -> None:

    async with _lock(chat_id):

        state = _state(chat_id)

        # ----------------------------------------------------
        # Ignore delayed event caused by manual skip/stop.
        # ----------------------------------------------------

        if state.suppress_next_end:

            state.suppress_next_end = False

            log.info(
                "MEDIA END: suppressed delayed "
                "stream_end chat=%s",
                chat_id,
            )

            return

        finished = state.current

        if finished:

            log.info(
                "MEDIA END: chat=%s title=%r "
                "repeat=%s",
                chat_id,
                finished.title,
                state.repeat,
            )

        # ----------------------------------------------------
        # Clean finished file.
        # ----------------------------------------------------

        if finished:
            await _cleanup_path(
                finished.temp_path
            )

        # ----------------------------------------------------
        # Repeat ONE
        # ----------------------------------------------------

        if (
            state.repeat == "one"
            and finished is not None
        ):

            state.current = MediaItem(
                chat_id=finished.chat_id,
                message_id=finished.message_id,
                title=finished.title,
                kind=finished.kind,
                requester_id=finished.requester_id,
                thread_id=finished.thread_id,
            )

        else:

            # ------------------------------------------------
            # Repeat ALL
            # ------------------------------------------------

            if (
                state.repeat == "all"
                and finished is not None
            ):
                # Clear temp path because the previous file
                # was deleted and must be downloaded again.
                finished.temp_path = None

                state.queue.append(
                    finished
                )

            state.current = None

        state.paused = False
        state.starting = False

        # ----------------------------------------------------
        # Start next item.
        # ----------------------------------------------------

        started = await _start_current(
            chat_id,
            None,
        )

        # ----------------------------------------------------
        # IMPORTANT:
        # If nothing is left, leave the voice chat.
        # ----------------------------------------------------

        if not started:
            state.current = None
            state.starting = False

            if not state.queue:

                log.info(
                    "MEDIA END: queue finished; "
                    "leaving chat=%s",
                    chat_id,
                )

                await _safe_leave(
                    chat_id
                )


# ============================================================
# ENQUEUE
# ============================================================

async def _enqueue(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
    mode: str = "auto",
) -> None:

    message = update.effective_message
    user = update.effective_user

    if not message or not user:
        return

    source = _source_message(update)
    media = _media_from_message(source)

    if source is None or media is None:

        await message.reply_text(
            "🎵 Reply to an audio or video message "
            "with <b>شغل</b> or <b>/play</b>.",
            parse_mode="HTML",
        )

        return

    detected_kind, title = media

    # --------------------------------------------------------
    # Determine requested playback mode.
    # --------------------------------------------------------

    if mode == "audio":

        # Any playable media can be forced to audio-only.
        kind = "audio"

    elif mode == "video":

        if detected_kind != "video":

            await message.reply_text(
                "❌ الأمر الخاص بالفيديو يحتاج إلى "
                "رسالة فيديو.",
            )

            return

        kind = "video"

    else:
        # AUTO:
        # audio stays audio.
        # video plays as video.
        kind = detected_kind

    state = _state(
        message.chat.id
    )

    if len(state.queue) >= MAX_QUEUE:

        await message.reply_text(
            f"❌ Queue is full. Maximum: {MAX_QUEUE} items."
        )

        return

    # The command's topic is the topic where the
    # controls should appear.
    thread_id = getattr(
        message,
        "message_thread_id",
        None,
    )

    # Fallback to the source media topic.
    if thread_id is None:
        thread_id = getattr(
            source,
            "message_thread_id",
            None,
        )

    item = MediaItem(
        chat_id=message.chat.id,
        message_id=source.message_id,
        title=title,
        kind=kind,
        requester_id=user.id,
        thread_id=thread_id,
    )

    async with _lock(
        message.chat.id
    ):

        state = _state(
            message.chat.id
        )

        # ----------------------------------------------------
        # Prevent duplicate media.
        # ----------------------------------------------------

        all_items = list(
            state.queue
        )

        if state.current:
            all_items.insert(
                0,
                state.current,
            )

        if any(
            x.message_id == item.message_id
            for x in all_items
        ):

            await message.reply_text(
                "ℹ️ This media is already in the player."
            )

            return

        # ----------------------------------------------------
        # Idle / Queue
        # ----------------------------------------------------

        was_idle = (
            state.current is None
            and not state.starting
        )

        if was_idle:
            state.current = item

        else:
            state.queue.append(
                item
            )

        position = (
            0
            if was_idle
            else len(state.queue)
        )

        # ----------------------------------------------------
        # Start immediately.
        # ----------------------------------------------------

        if was_idle:

            mode_text = (
                "🎬 Video + audio"
                if kind == "video"
                else "🎵 Audio"
            )

            await message.reply_text(
                f"▶️ Starting: "
                f"<b>{title}</b>\n"
                f"🎧 Mode: {mode_text}",
                parse_mode="HTML",
            )

            started = await _start_current(
                message.chat.id,
                context,
            )

            if not started:

                await message.reply_text(
                    "❌ Playback could not be started.\n"
                    "Check the Render logs for "
                    "MEDIA ENGINE / MEDIA DOWNLOAD / "
                    "MEDIA START."
                )

            return

        # ----------------------------------------------------
        # Added to queue.
        # ----------------------------------------------------

        await message.reply_text(
            f"➕ Added to queue: "
            f"<b>{title}</b>\n"
            f"📍 Position: {position}",
            parse_mode="HTML",
        )


